-- V1: Baseline schema.
--
-- This captures the schema the JPA entities describe. It is only RUN on a brand-new,
-- empty database. An existing database (such as production, which was created by
-- Hibernate's ddl-auto=update) is *baselined* at version 1 by Flyway
-- (spring.flyway.baseline-on-migrate=true) and this script is skipped for it.
--
-- Keep this file immutable. All later schema changes go in V2, V3, ... as new files.
-- Portable SQL only (no Postgres-only functions) so it also runs on H2 in tests.
-- ${text_type} is a Flyway placeholder: TEXT in production (see application.properties),
-- a large VARCHAR in the H2 test that checks this script against the entities.

-- ── auth ────────────────────────────────────────────────────────────────────
CREATE TABLE users (
    id              UUID         PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    username        VARCHAR(100) UNIQUE,
    password_hash   VARCHAR(255),
    first_name      VARCHAR(100),
    last_name       VARCHAR(100),
    name            VARCHAR(255),
    google_id       VARCHAR(255) UNIQUE,
    profile_picture VARCHAR(500),
    role            VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL
);

CREATE TABLE refresh_tokens (
    id          UUID         PRIMARY KEY,
    user_id     UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,   -- SHA-256 hex of the raw token
    expires_at  TIMESTAMP(6) NOT NULL,
    used        BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL
);

-- ── transactions ────────────────────────────────────────────────────────────
CREATE TABLE transactions (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        VARCHAR(255)  NOT NULL,
    description    VARCHAR(500)  NOT NULL,
    amount         NUMERIC(38,2) NOT NULL,
    merchant       VARCHAR(255),
    category       VARCHAR(100),
    type           VARCHAR(20)   NOT NULL,       -- INCOME or EXPENSE
    date           DATE          NOT NULL,
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    ml_predicted   BOOLEAN       NOT NULL,
    status         VARCHAR(20)   DEFAULT 'completed',
    notes          VARCHAR(1000),
    tags           VARCHAR(500),
    payment_method VARCHAR(100)
);

CREATE TABLE recurring_transactions (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         VARCHAR(255)  NOT NULL,
    description     VARCHAR(500)  NOT NULL,
    amount          NUMERIC(38,2) NOT NULL,
    merchant        VARCHAR(255),
    category        VARCHAR(100),
    type            VARCHAR(20)   NOT NULL,
    frequency       VARCHAR(20)   NOT NULL,      -- DAILY, WEEKLY, MONTHLY, YEARLY
    start_date      DATE          NOT NULL,
    end_date        DATE,
    next_occurrence DATE          NOT NULL,
    active          BOOLEAN       NOT NULL,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6)
);

-- ── budgets & goals ─────────────────────────────────────────────────────────
CREATE TABLE budgets (
    id         BIGINT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    VARCHAR(255)     NOT NULL,
    category   VARCHAR(255)     NOT NULL,
    budget     DOUBLE PRECISION NOT NULL,
    spent      DOUBLE PRECISION NOT NULL,
    month      VARCHAR(255)     NOT NULL,
    icon       VARCHAR(10),
    period     VARCHAR(255),
    color      VARCHAR(20),
    is_active  BOOLEAN          NOT NULL,
    start_date TIMESTAMP(6),
    end_date   TIMESTAMP(6),
    created_at TIMESTAMP(6)     NOT NULL,
    updated_at TIMESTAMP(6)
);

CREATE TABLE goals (
    id                   VARCHAR(255)  PRIMARY KEY,
    user_id              VARCHAR(255)  NOT NULL,
    name                 VARCHAR(255)  NOT NULL,
    target_amount        NUMERIC(15,2) NOT NULL,
    current_amount       NUMERIC(15,2),
    deadline             DATE,
    category             VARCHAR(255),
    icon                 VARCHAR(255)  NOT NULL,
    color                VARCHAR(255)  NOT NULL,
    monthly_contribution NUMERIC(15,2),
    achieved             BOOLEAN       NOT NULL,
    created_at           TIMESTAMP(6),
    updated_at           TIMESTAMP(6)
);

-- ── alerts ──────────────────────────────────────────────────────────────────
CREATE TABLE alerts (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      VARCHAR(255),
    message      VARCHAR(255),
    type         VARCHAR(255),
    status       VARCHAR(255),
    priority     VARCHAR(255),
    title        VARCHAR(255),
    severity     VARCHAR(255),
    category     VARCHAR(255),
    read         BOOLEAN      NOT NULL,
    acknowledged BOOLEAN      NOT NULL,
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6)
);

CREATE TABLE alert_rules (
    id               UUID          PRIMARY KEY,
    user_id          UUID          NOT NULL,
    rule_type        VARCHAR(255)  NOT NULL,
    threshold_amount NUMERIC(38,2) NOT NULL,
    category         VARCHAR(255),
    is_active        BOOLEAN       NOT NULL,
    created_at       TIMESTAMP(6)  NOT NULL,
    updated_at       TIMESTAMP(6)
);

CREATE TABLE alert_history (
    id         UUID          PRIMARY KEY,
    user_id    UUID          NOT NULL,
    rule_id    UUID,
    alert_type VARCHAR(255)  NOT NULL,
    severity   VARCHAR(255)  NOT NULL,
    message    VARCHAR(1000) NOT NULL,
    metadata   ${text_type},
    is_read    BOOLEAN       NOT NULL,
    created_at TIMESTAMP(6)  NOT NULL
);

CREATE TABLE notification_log (
    id            UUID          PRIMARY KEY,
    alert_id      UUID          NOT NULL,
    channel       VARCHAR(255)  NOT NULL,
    recipient     VARCHAR(255)  NOT NULL,
    status        VARCHAR(255)  NOT NULL,
    error_message VARCHAR(1000),
    sent_at       TIMESTAMP(6),
    created_at    TIMESTAMP(6)  NOT NULL
);

-- ── notifications ───────────────────────────────────────────────────────────
CREATE TABLE notifications (
    id         UUID                        PRIMARY KEY,
    user_id    VARCHAR(128)                NOT NULL,
    title      VARCHAR(160)                NOT NULL,
    message    VARCHAR(2000)               NOT NULL,
    type       VARCHAR(48)                 NOT NULL,
    read       BOOLEAN                     NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notifications_user      ON notifications (user_id);
CREATE INDEX idx_notifications_user_read ON notifications (user_id, read);

CREATE TABLE notification_settings (
    user_id                      VARCHAR(128) PRIMARY KEY,
    email_enabled                BOOLEAN      NOT NULL,
    push_enabled                 BOOLEAN      NOT NULL,
    budget_alerts_enabled        BOOLEAN      NOT NULL,
    transaction_alerts_enabled   BOOLEAN      NOT NULL,
    system_notifications_enabled BOOLEAN      NOT NULL
);

-- ── reports ─────────────────────────────────────────────────────────────────
CREATE TABLE report_history (
    id           UUID         PRIMARY KEY,
    user_id      UUID         NOT NULL,
    report_type  VARCHAR(255) NOT NULL,
    status       VARCHAR(255) NOT NULL,
    generated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE scheduled_reports (
    id              UUID         PRIMARY KEY,
    user_id         UUID         NOT NULL,
    report_type     VARCHAR(50)  NOT NULL,
    frequency       VARCHAR(20)  NOT NULL,       -- DAILY, WEEKLY, MONTHLY
    start_date      DATE         NOT NULL,
    end_date        DATE,
    format          VARCHAR(20),                 -- PDF, EXCEL, JSON
    categories      ${text_type},                        -- JSON array stored as text
    delivery_method VARCHAR(20),                 -- EMAIL, DOWNLOAD
    delivery_email  VARCHAR(255),
    active          BOOLEAN      NOT NULL,
    last_run        TIMESTAMP(6),
    next_run        TIMESTAMP(6),
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6)
);

CREATE TABLE transaction_aggregates (
    id                UUID          PRIMARY KEY,
    user_id           UUID          NOT NULL,
    aggregation_date  DATE          NOT NULL,
    aggregation_type  VARCHAR(20)   NOT NULL,
    category          VARCHAR(100),
    total_amount      NUMERIC(15,2) NOT NULL,
    transaction_count INTEGER       NOT NULL,
    avg_amount        NUMERIC(15,2),
    max_amount        NUMERIC(15,2),
    min_amount        NUMERIC(15,2),
    updated_at        TIMESTAMP(6)
);

CREATE TABLE spending_summary_cache (
    id           UUID          PRIMARY KEY,
    user_id      UUID          NOT NULL,
    period_type  VARCHAR(20)   NOT NULL,
    period_start DATE          NOT NULL,
    period_end   DATE          NOT NULL,
    total_amount NUMERIC(19,2),
    data         ${text_type},
    expires_at   TIMESTAMP(6)  NOT NULL,
    created_at   TIMESTAMP(6)  NOT NULL,
    updated_at   TIMESTAMP(6)  NOT NULL
);
